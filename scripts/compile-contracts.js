/**
 * QC RocketStart - Contract Compilation Script
 * 
 * Compiles FunC contracts to BOC bytecode using @ton-community/func-js
 */

const { compileFunc } = require("@ton-community/func-js");
const fs = require("fs");
const path = require("path");

const CONTRACTS_DIR = path.join(__dirname, "../contracts");
const OUTPUT_DIR = path.join(CONTRACTS_DIR, "build");

async function compileContract(name, mainFile) {
    console.log(`\n📦 Compiling ${name}...`);

    const result = await compileFunc({
        targets: [mainFile],
        sources: (filePath) => {
            // Handle stdlib
            if (filePath.includes("stdlib.fc")) {
                const stdlibPath = path.join(CONTRACTS_DIR, "imports", "stdlib.fc");
                if (fs.existsSync(stdlibPath)) {
                    return fs.readFileSync(stdlibPath, "utf-8");
                }
                return null;
            }

            // Handle main contract files
            const fullPath = path.join(CONTRACTS_DIR, filePath);
            if (fs.existsSync(fullPath)) {
                return fs.readFileSync(fullPath, "utf-8");
            }

            console.error(`File not found: ${fullPath}`);
            return null;
        },
    });

    if (result.status === "error") {
        console.error(`❌ Compilation failed for ${name}:`);
        console.error(result.message);
        throw new Error(result.message);
    }

    console.log(`✅ ${name} compiled successfully`);
    return Buffer.from(result.codeBoc, "base64");
}

async function main() {
    console.log("🚀 QC RocketStart Contract Compiler");
    console.log("====================================\n");

    // Ensure output directory exists
    if (!fs.existsSync(OUTPUT_DIR)) {
        fs.mkdirSync(OUTPUT_DIR, { recursive: true });
    }

    try {
        // Compile Jetton Wallet first (it's used by Master)
        const walletCode = await compileContract("JettonWallet", "jetton_wallet.fc");
        const walletBocPath = path.join(OUTPUT_DIR, "jetton_wallet.boc");
        fs.writeFileSync(walletBocPath, walletCode);
        console.log(`   Saved: ${walletBocPath}`);

        // Compile Jetton Master
        const masterCode = await compileContract("JettonMaster", "jetton_master.fc");
        const masterBocPath = path.join(OUTPUT_DIR, "jetton_master.boc");
        fs.writeFileSync(masterBocPath, masterCode);
        console.log(`   Saved: ${masterBocPath}`);

        // Generate hex strings for TypeScript
        const walletHex = walletCode.toString("hex");
        const masterHex = masterCode.toString("hex");

        const tsOutput = `/**
 * Compiled Contract Bytecode
 * Generated: ${new Date().toISOString()}
 * 
 * DO NOT EDIT MANUALLY - Auto-generated by scripts/compile-contracts.js
 */

export const JETTON_MASTER_CODE_HEX = "${masterHex}";
export const JETTON_WALLET_CODE_HEX = "${walletHex}";
`;

        const codeTsPath = path.join(OUTPUT_DIR, "contract-code.ts");
        fs.writeFileSync(codeTsPath, tsOutput);
        console.log(`   Saved: ${codeTsPath}`);

        console.log("\n====================================");
        console.log("✅ All contracts compiled successfully!");
        console.log("\n📁 Output files:");
        console.log(`   ${walletBocPath} (${walletCode.length} bytes)`);
        console.log(`   ${masterBocPath} (${masterCode.length} bytes)`);
        console.log(`   ${codeTsPath}`);
        console.log("\n💡 Now update lib/jetton-real.ts to import from contracts/build/contract-code.ts");

    } catch (error) {
        console.error("\n❌ Compilation failed:", error.message);
        process.exit(1);
    }
}

main();
